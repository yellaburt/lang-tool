// ===== Normalisation =====

const LETTERS = /[a-záéíóúüñ]+/g;

function words(span: string): string[] {
  return span.toLowerCase().match(LETTERS) ?? [];
}

// Leading material the model sometimes includes in a verb span: negation and
// proclitic pronouns ("No me digas", "que te vaya").
const SPAN_PREFIX = new Set(['no', 'me', 'te', 'se', 'nos', 'os', 'le', 'les', 'lo', 'la', 'los', 'las', 'que']);

// The verb words of a span, with leading negation/clitics stripped.
function verbWords(span: string): string[] {
  const ws = words(span);
  while (ws.length > 1 && SPAN_PREFIX.has(ws[0]!)) ws.shift();
  return ws;
}

// "recuperarse" → "recuperar"; trims, lowercases. Returns null for anything
// that isn't shaped like an infinitive.
export function normalizeLemma(raw: string): string | null {
  let l = raw.trim().toLowerCase();
  if (/(ar|er|ir|ír)se$/.test(l)) l = l.slice(0, -2);
  return /^[a-záéíóúüñ]*(ar|er|ir|ír)$/.test(l) ? l : null;
}

function verbClass(lemma: string): 'ar' | 'er' | 'ir' {
  if (lemma.endsWith('ar')) return 'ar';
  if (lemma.endsWith('er')) return 'er';
  return 'ir';
}

// ===== Spec lookup =====

function prefixed(prefix: string, e: IrregularEntry): IrregularEntry {
  return {
    ...(e.stemChange ? { stemChange: e.stemChange } : {}),
    ...(e.presentStem ? { presentStem: prefix + e.presentStem } : {}),
    ...(e.presentForms ? { presentForms: e.presentForms.map((f) => prefix + f) } : {}),
    ...(e.pret3pl ? { pret3pl: prefix + e.pret3pl } : {}),
    ...(e.participles ? { participles: e.participles.map((p) => prefix + p) } : {}),
  };
}

function irregularEntry(lemma: string): IrregularEntry | null {
  const exact = IRREGULAR[lemma];
  if (exact) return exact;
  for (const [base, prefixes] of IRREGULAR_FAMILIES) {
    if (!lemma.endsWith(base)) continue;
    const prefix = lemma.slice(0, -base.length);
    if (prefixes.includes(prefix)) return prefixed(prefix, IRREGULAR[base]!);
  }
  return null;
}

let knownFlags: Map<string, string> | null = null;
function knownVerbFlags(): Map<string, string> {
  if (knownFlags) return knownFlags;
  knownFlags = new Map();
  for (const tok of KNOWN_VERBS.split(/\s+/)) {
    if (!tok) continue;
    const [lemma, flag] = tok.split(':');
    knownFlags.set(lemma!, flag ?? '');
  }
  for (const l of Object.keys(IRREGULAR)) if (!knownFlags.has(l)) knownFlags.set(l, '');
  return knownFlags;
}

export function isKnownLemma(lemma: string): boolean {
  return knownVerbFlags().has(lemma);
}

function specFromFlag(lemma: string, flag: string): VerbSpec {
  const irr = irregularEntry(lemma);
  const stemChange: StemChange =
    flag === 'ie' || flag === 'ue' || flag === 'i' || flag === 'ie-i' || flag === 'ue-u'
      ? flag
      : (irr?.stemChange ?? 'none');
  return { ...irr, lemma, stemChange, accented: flag === 'acc' };
}

// Every spec worth trying for a lemma. Known lemmas have exactly one. For a
// lemma we've never seen, we don't know its stem-change class, so we try all of
// them: a correct tag on an unknown stem-changer then survives the veto, while
// a token no class could produce (portas, recuperó) still fails it.
function specsFor(lemma: string): VerbSpec[] {
  const flag = knownVerbFlags().get(lemma);
  if (flag !== undefined) return [specFromFlag(lemma, flag)];
  if (irregularEntry(lemma)) return [specFromFlag(lemma, '')];
  const cls = verbClass(lemma);
  const classes: StemChange[] =
    cls === 'ir' ? ['none', 'ie', 'ue', 'i', 'ie-i', 'ue-u'] : ['none', 'ie', 'ue'];
  const specs: VerbSpec[] = classes.map((c) => ({ lemma, stemChange: c, accented: false }));
  specs.push({ lemma, stemChange: 'none', accented: true });
  return specs;
}

// ===== Stem helpers =====

function replaceLast(stem: string, from: RegExp, to: string): string {
  let idx = -1;
  for (let i = stem.length - 1; i >= 0; i--) {
    if (from.test(stem[i]!)) {
      idx = i;
      break;
    }
  }
  return idx < 0 ? stem : stem.slice(0, idx) + to + stem.slice(idx + 1);
}

// Stem change in the stressed ("boot") forms: 1sg, 2sg, 3sg, 3pl.
function bootChange(stem: string, sc: StemChange): string {
  switch (sc) {
    case 'none':
      return stem;
    case 'ie':
    case 'ie-i':
      // adquirir / inquirir: the changing vowel is i, not e.
      return /e/.test(stem) ? replaceLast(stem, /e/, 'ie') : replaceLast(stem, /i/, 'ie');
    case 'ue':
    case 'ue-u':
      // jugar is the lone u → ue verb.
      return /o/.test(stem) ? replaceLast(stem, /o/, 'ue') : replaceLast(stem, /u/, 'ue');
    case 'i':
      return replaceLast(stem, /e/, 'i');
  }
}

// -ir stem-changers also change in nosotros/vosotros (sintamos, durmamos,
// pidamos) and in the 3rd-person preterite (sintieron, durmieron).
function weakChange(stem: string, sc: StemChange): string {
  if (sc === 'i' || sc === 'ie-i') return replaceLast(stem, /e/, 'i');
  if (sc === 'ue-u') return replaceLast(stem, /o/, 'u');
  return stem;
}

function accentWeakVowel(stem: string): string {
  for (let i = stem.length - 1; i >= 0; i--) {
    const c = stem[i];
    if (c === 'i' || c === 'u') return stem.slice(0, i) + (c === 'i' ? 'í' : 'ú') + stem.slice(i + 1);
  }
  return stem;
}

// Spelling changes that keep the stem's sound before the subjunctive endings.
function orthography(stem: string, lemma: string): string {
  const cls = verbClass(lemma);
  if (cls === 'ar') {
    if (stem.endsWith('gu')) return stem.slice(0, -2) + 'gü'; // averiguar → averigüe
    if (stem.endsWith('c')) return stem.slice(0, -1) + 'qu'; // buscar → busque
    if (stem.endsWith('g')) return stem + 'u'; // llegar → llegue
    if (stem.endsWith('z')) return stem.slice(0, -1) + 'c'; // cruzar → cruce
    return stem;
  }
  if (stem.endsWith('gu') && lemma.endsWith('guir')) return stem.slice(0, -1); // seguir → siga
  if (stem.endsWith('qu') && lemma.endsWith('quir')) return stem.slice(0, -2) + 'c';
  if (stem.endsWith('g')) return stem.slice(0, -1) + 'j'; // coger → coja
  if (stem.endsWith('c')) {
    const before = stem[stem.length - 2] ?? '';
    const afterVowel = /[aeiouáéíóú]/.test(before);
    return stem.slice(0, -1) + (afterVowel && !Z_NOT_ZC.has(lemma) ? 'zc' : 'z');
  }
  if (lemma.endsWith('uir') && !/[gq]uir$/.test(lemma)) return stem + 'y'; // construir → construya
  return stem;
}

// ===== Generation =====

const AR_PRESENT = ['e', 'es', 'e', 'emos', 'éis', 'en'];
const ER_PRESENT = ['a', 'as', 'a', 'amos', 'áis', 'an'];

function presentSubjunctive(spec: VerbSpec): string[] {
  if (spec.presentForms) return [...spec.presentForms];
  const endings = verbClass(spec.lemma) === 'ar' ? AR_PRESENT : ER_PRESENT;
  const base = spec.lemma.slice(0, -2);
  return PERSONS.map((p, i) => {
    if (spec.presentStem) return spec.presentStem + endings[i]!;
    const boot = p !== '1pl' && p !== '2pl';
    let stem = boot
      ? bootChange(base, spec.stemChange)
      : verbClass(spec.lemma) === 'ir'
        ? weakChange(base, spec.stemChange)
        : base;
    if (spec.accented && boot) stem = accentWeakVowel(stem);
    return orthography(stem, spec.lemma) + endings[i]!;
  });
}

function preterite3pl(spec: VerbSpec): string {
  if (spec.pret3pl) return spec.pret3pl;
  const cls = verbClass(spec.lemma);
  let stem = spec.lemma.slice(0, -2);
  if (cls === 'ar') return stem + 'aron';
  if (spec.lemma.endsWith('ducir')) return stem.slice(0, -1) + 'jeron'; // conducir → condujeron
  if (cls === 'ir') stem = weakChange(stem, spec.stemChange);
  if (/[aeo]$/.test(stem) || (/u$/.test(stem) && !/[gq]u$/.test(stem))) {
    return stem + 'yeron'; // leyeron, construyeron
  }
  if (/(ñ|ll)$/.test(stem)) return stem + 'eron'; // gruñeron
  return stem + 'ieron';
}

const STRESS: Readonly<Record<string, string>> = { a: 'á', e: 'é', i: 'í', o: 'ó', u: 'ú' };

function imperfectSubjunctive(spec: VerbSpec, kind: 'ra' | 'se'): string[] {
  const base = preterite3pl(spec).slice(0, -3); // hablaron → habla
  const stressed = base.slice(0, -1) + (STRESS[base.slice(-1)] ?? base.slice(-1));
  // -ra: ra ras ra ramos rais ran; -se: se ses se semos seis sen.
  const s = kind === 'ra' ? 'ra' : 'se';
  return [
    `${base}${s}`,
    `${base}${s}s`,
    `${base}${s}`,
    `${stressed}${s}mos`,
    `${base}${kind === 'ra' ? 'rais' : 'seis'}`,
    `${base}${s}n`,
  ];
}

export function participlesOf(lemma: string): string[] {
  const exact = PARTICIPLE_EXACT[lemma];
  if (exact) return [...exact];
  const irr = irregularEntry(lemma);
  if (irr?.participles) return [...irr.participles];
  if (lemma === 'bendecir' || lemma === 'maldecir') return [lemma.slice(0, -2) + 'ido'];
  for (const [suffix, part] of PARTICIPLE_SUFFIXES) {
    if (lemma.endsWith(suffix)) return [lemma.slice(0, -suffix.length) + part];
  }
  const stem = lemma.slice(0, -2);
  if (verbClass(lemma) === 'ar') return [stem + 'ado'];
  return [/[aeo]$/.test(stem) ? stem + 'ído' : stem + 'ido'];
}

// Every single-word subjunctive form of a lemma (present, imperfect -ra/-se).
// Compound tenses are two words and are matched separately (matchSubjunctive).
export function subjunctiveForms(rawLemma: string): SubjForm[] {
  const lemma = normalizeLemma(rawLemma);
  if (!lemma) return [];
  const out: SubjForm[] = [];
  const seen = new Set<string>();
  for (const spec of specsFor(lemma)) {
    const tables: ReadonlyArray<readonly [SubjTense, string[]]> = [
      ['present', presentSubjunctive(spec)],
      ['imperfect-ra', imperfectSubjunctive(spec, 'ra')],
      ['imperfect-se', imperfectSubjunctive(spec, 'se')],
    ];
    for (const [tense, forms] of tables) {
      forms.forEach((form, i) => {
        const key = `${form}|${tense}|${i}`;
        if (seen.has(key)) return;
        seen.add(key);
        out.push({ form, lemma, tense, person: PERSONS[i]! });
      });
    }
  }
  return out;
}

const COMPOUND_TENSE: Readonly<Partial<Record<SubjTense, SubjTense>>> = {
  present: 'perfect',
  'imperfect-ra': 'pluperfect-ra',
  'imperfect-se': 'pluperfect-se',
};

function collect(matches: ReadonlyArray<SubjForm>): SubjMatch | null {
  const first = matches[0];
  if (!first) return null;
  // If one token is two different tenses at once (never happens for a single
  // lemma in practice), report the first; persons are merged within it.
  const same = matches.filter((m) => m.tense === first.tense);
  return {
    lemma: first.lemma,
    tense: first.tense,
    persons: [...new Set(same.map((m) => m.person))],
  };
}

// Is `span` a subjunctive form of `lemma`? Handles one-word forms and the
// compound tenses (haber in the subjunctive + a participle of the lemma). The
// comparison is accent-sensitive: "hable" and "hablé" are different words.
export function matchSubjunctive(span: string, rawLemma: string): SubjMatch | null {
  const lemma = normalizeLemma(rawLemma);
  if (!lemma) return null;
  const ws = verbWords(span);
  if (ws.length === 1) {
    return collect(subjunctiveForms(lemma).filter((f) => f.form === ws[0]));
  }
  if (ws.length === 2) {
    const aux = collect(subjunctiveForms('haber').filter((f) => f.form === ws[0]));
    const tense = aux ? COMPOUND_TENSE[aux.tense] : undefined;
    if (!aux || !tense) return null;
    // The model may name the lexical verb (escribir) or the auxiliary (haber).
    const participleOk =
      participlesOf(lemma).includes(ws[1]!) ||
      (lemma === 'haber' && /(ado|ido|ído|to|cho|so)$/.test(ws[1]!));
    return participleOk ? { lemma, tense, persons: aux.persons } : null;
  }
  return null;
}

// ===== Reverse lookup =====

let reverseIndex: Map<string, SubjForm[]> | null = null;
let indicativeCollisions: Set<string> | null = null;

function buildReverseIndex(): void {
  reverseIndex = new Map();
  indicativeCollisions = new Set();
  const indicative = new Set<string>();
  for (const lemma of knownVerbFlags().keys()) {
    for (const f of subjunctiveForms(lemma)) {
      const list = reverseIndex.get(f.form) ?? [];
      list.push(f);
      reverseIndex.set(f.form, list);
    }
    // Present indicative 2sg…3pl — the only indicative forms that can collide
    // with another verb's subjunctive (sienta: sentar indicative / sentir
    // subjunctive). Irregular present tables are skipped; none of them collide.
    const spec = specFromFlag(lemma, knownVerbFlags().get(lemma) ?? '');
    if (spec.presentForms || spec.presentStem) continue;
    const cls = verbClass(lemma);
    const base = lemma.slice(0, -2);
    const endings =
      cls === 'ar'
        ? ['as', 'a', 'amos', 'áis', 'an']
        : cls === 'er'
          ? ['es', 'e', 'emos', 'éis', 'en']
          : ['es', 'e', 'imos', 'ís', 'en'];
    endings.forEach((end, i) => {
      const boot = i !== 2 && i !== 3;
      let stem = boot ? bootChange(base, spec.stemChange) : base;
      if (spec.accented && boot) stem = accentWeakVowel(stem);
      indicative.add(stem + end);
    });
  }
  for (const form of reverseIndex.keys()) {
    if (indicative.has(form)) indicativeCollisions.add(form);
  }
}

// All subjunctive analyses of a single token among KNOWN_VERBS. Empty when the
// token isn't a known subjunctive form.
export function analyzeToken(token: string): SubjForm[] {
  if (!reverseIndex) buildReverseIndex();
  return reverseIndex!.get(token.toLowerCase()) ?? [];
}

export function isHomograph(token: string): boolean {
  if (!indicativeCollisions) buildReverseIndex();
  const t = token.toLowerCase();
  return HOMOGRAPHS.has(t) || indicativeCollisions!.has(t);
}

// An analysis the lexicon will stand behind with no model input: a known
// subjunctive form, not a homograph, one tense. Several lemmas are fine as
// long as they agree on tense (fuera: ser or ir, both imperfect).
export function unambiguousAnalysis(token: string): SubjMatch | null {
  if (isHomograph(token)) return null;
  const all = analyzeToken(token);
  const first = all[0];
  if (!first || all.some((a) => a.tense !== first.tense)) return null;
  const lemmas = [...new Set(all.map((a) => a.lemma))];
  return {
    lemma: lemmas.join(' / '),
    tense: first.tense,
    persons: [...new Set(all.map((a) => a.person))],
  };
}

// ===== Human-readable descriptions =====

const TENSE_LABEL: Readonly<Record<SubjTense, string>> = {
  present: 'present subjunctive',
  'imperfect-ra': 'imperfect subjunctive (-ra form)',
  'imperfect-se': 'imperfect subjunctive (-se form)',
  perfect: 'present perfect subjunctive',
  'pluperfect-ra': 'pluperfect subjunctive (-ra form)',
  'pluperfect-se': 'pluperfect subjunctive (-se form)',
};

const PERSON_LABEL: Readonly<Record<PersonNumber, string>> = {
  '1sg': '1st person singular',
  '2sg': '2nd person singular',
  '3sg': '3rd person singular',
  '1pl': '1st person plural',
  '2pl': '2nd person plural',
  '3pl': '3rd person plural',
};

export function describeMatch(m: SubjMatch): string {
  const persons = m.persons.map((p) => PERSON_LABEL[p]).join(' or ');
  return `${m.lemma}, ${TENSE_LABEL[m.tense]}, ${persons}`;
}

export function isPastTense(t: SubjTense): boolean {
  return t !== 'present' && t !== 'perfect';
}

// ===== Pre-scan for gloss facts (item 5) =====

export interface LexiconFact {
  readonly token: string;
  readonly match: SubjMatch;
}

// Distinct tokens in `text` the lexicon identifies unambiguously as
// subjunctive. Handed to the gloss prompt as given facts, so a correctly
// highlighted "aullaran" can't be glossed as the future "aullarán".
export function scanLexiconFacts(text: string): LexiconFact[] {
  const facts: LexiconFact[] = [];
  const seen = new Set<string>();
  for (const w of text.match(/[A-Za-zÁÉÍÓÚÜÑáéíóúüñ]+/g) ?? []) {
    const t = w.toLowerCase();
    if (seen.has(t)) continue;
    seen.add(t);
    const match = unambiguousAnalysis(t);
    if (match) facts.push({ token: w, match });
  }
  return facts;
}

export function formatLexiconFacts(facts: ReadonlyArray<LexiconFact>): string {
  return facts.map((f) => `- "${f.token}": ${describeMatch(f.match)}`).join('\n');
}

// ===== Post-pass over resolved model annotations =====

export type MoodRole = 'trigger' | 'subjunctive_verb' | 'possible_subjunctive';

export interface CandidateAnnotation {
  readonly start: number;
  readonly end: number;
  readonly role: MoodRole;
  readonly pairId: number;
  readonly lemma?: string;
}

export interface CheckedAnnotation {
  readonly start: number;
  readonly end: number;
  readonly role: MoodRole;
  readonly pairId: number;
  readonly lemma?: string;
  readonly tense?: SubjTense;
}

// A case where the model's reading and the lexicon's differ. Written to the
// mood review log (never silently resolved in the data the reader can't see):
// recurring disagreement on one lemma means that lexicon entry needs an audit.
export interface LexiconDisagreement {
  readonly lemma: string;
  readonly token: string;
  readonly lexiconAnswer: string;
  readonly modelAnswer: string;
}

// Apply the lexicon to one chunk's annotations:
//   - Veto (item 4): every verb tag must be a subjunctive form of the lemma
//     the model named, or it's dropped — confident tags included, since the
//     observed errors (se recuperó, portas) came through as confident.
//   - Uncertain tags (item 3): promoted to subjunctive_verb when the token is
//     an unambiguous form, kept as possible_subjunctive when it's a homograph.
//   - Lexicon authority (item 5): an unambiguous known form the model left
//     untagged is tagged anyway, as a solo verb.
//   - Trigger guard (item 1): a trigger with no subjunctive_verb sharing its
//     pairId in this chunk is dropped.
export function applyLexicon(
  tlText: string,
  candidates: ReadonlyArray<CandidateAnnotation>,
): { annotations: CheckedAnnotation[]; disagreements: LexiconDisagreement[] } {
  const disagreements: LexiconDisagreement[] = [];
  const verbs: CheckedAnnotation[] = [];
  for (const a of candidates) {
    if (a.role === 'trigger') continue;
    const span = tlText.slice(a.start, a.end);
    const match = a.lemma ? matchSubjunctive(span, a.lemma) : null;
    if (!match) {
      disagreements.push({
        lemma: a.lemma ?? '',
        token: span,
        lexiconAnswer: a.lemma
          ? `not a subjunctive form of ${a.lemma}`
          : 'no lemma given; cannot verify',
        modelAnswer: a.role === 'subjunctive_verb' ? 'subjunctive' : 'possibly subjunctive',
      });
      continue;
    }
    // A confident tag that passed the veto stays confident. An uncertain one is
    // promoted unless the verb is a single homograph word; compound tenses
    // (haya + participle) are never homographs.
    const vw = verbWords(span);
    const role: MoodRole =
      a.role === 'subjunctive_verb' || vw.length > 1 || !isHomograph(vw[0] ?? '')
        ? 'subjunctive_verb'
        : 'possible_subjunctive';
    verbs.push({ start: a.start, end: a.end, role, pairId: a.pairId, lemma: match.lemma, tense: match.tense });
  }

  // Unambiguous known forms the model didn't tag at all.
  let nextPair = Math.max(0, ...candidates.map((c) => c.pairId)) + 1;
  const re = /[A-Za-zÁÉÍÓÚÜÑáéíóúüñ]+/g;
  let m: RegExpExecArray | null;
  while ((m = re.exec(tlText)) !== null) {
    const start = m.index;
    const end = start + m[0].length;
    if (verbs.some((v) => start < v.end && v.start < end)) continue;
    const match = unambiguousAnalysis(m[0]);
    if (!match) continue;
    const vetoed = disagreements.some((d) => d.token.toLowerCase().includes(m![0].toLowerCase()));
    if (vetoed) continue;
    disagreements.push({
      lemma: match.lemma,
      token: m[0],
      lexiconAnswer: describeMatch(match),
      modelAnswer: 'not tagged as subjunctive',
    });
    verbs.push({
      start,
      end,
      role: 'subjunctive_verb',
      pairId: nextPair++,
      lemma: match.lemma,
      tense: match.tense,
    });
  }

  const licensed = new Set(verbs.filter((v) => v.role === 'subjunctive_verb').map((v) => v.pairId));
  const triggers: CheckedAnnotation[] = candidates
    .filter((a) => a.role === 'trigger' && licensed.has(a.pairId))
    .map((a) => ({ start: a.start, end: a.end, role: a.role, pairId: a.pairId }));

  const annotations = [...triggers, ...verbs].sort((x, y) => x.start - y.start);
  return { annotations, disagreements };
}
