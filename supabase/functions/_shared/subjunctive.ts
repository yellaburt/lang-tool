// Deterministic Spanish subjunctive lexicon + the mood-annotation post-pass.
//
// Shared by the chunk-and-gloss Edge Function (imported as
// '../_shared/subjunctive.ts') and the client test suite (imported from src/
// without the extension). Pure data + pure functions only — no Deno or DOM
// APIs, no imports — so both runtimes can load it unchanged. Unlike the prompt
// in src/prompt.ts, this is NOT duplicated: there is one copy.
//
// What it does:
//   1. Generates subjunctive conjugation tables per lemma: present, imperfect
//      (-ra and -se), perfect and pluperfect (-ra and -se), with person/number
//      for each form. Regular verbs are generated by rule (including the
//      c→qu / g→gu / z→c / g→j / c→zc spelling changes); stem-changers carry a
//      class flag; true irregulars live in a table.
//   2. Vetoes model `subjunctive_verb` tags whose token is not a subjunctive
//      form of the lemma the model named (task item 4).
//   3. Resolves the model's uncertain tags into `subjunctive_verb` (unambiguous
//      lexicon match) or `possible_subjunctive` (a homograph) (item 3).
//   4. Pre-scans Spanish input for forms the lexicon is sure about, so they can
//      be handed to the gloss prompt as given facts (item 5).
//
// Coverage: generation works for any regular-shaped lemma the model names, so
// the veto (which always has a model lemma) is broad. Reverse lookup — finding
// forms in text with no lemma given — only covers KNOWN_VERBS below, because a
// guessed lemma can't be verified. Tokens outside that list are "outside
// lexicon coverage" in the sense of the task doc: the model glosses them alone.

export type SubjTense =
  | 'present'
  | 'imperfect-ra'
  | 'imperfect-se'
  | 'perfect'
  | 'pluperfect-ra'
  | 'pluperfect-se';

export type PersonNumber = '1sg' | '2sg' | '3sg' | '1pl' | '2pl' | '3pl';

const PERSONS: ReadonlyArray<PersonNumber> = ['1sg', '2sg', '3sg', '1pl', '2pl', '3pl'];

export interface SubjForm {
  readonly form: string;
  readonly lemma: string;
  readonly tense: SubjTense;
  readonly person: PersonNumber;
}

// A span matched against the lexicon. `persons` has more than one entry when
// the form is shared (hable = 1sg and 3sg).
export interface SubjMatch {
  readonly lemma: string;
  readonly tense: SubjTense;
  readonly persons: ReadonlyArray<PersonNumber>;
}

// ===== Verb specs =====

// Stem-change class. 'ie-i' / 'ue-u' are the -ir verbs whose nosotros/vosotros
// forms and 3rd-person preterite also change (sentir → sintamos, sintieron).
type StemChange = 'none' | 'ie' | 'ue' | 'i' | 'ie-i' | 'ue-u';

interface VerbSpec {
  readonly lemma: string;
  readonly stemChange: StemChange;
  // enviar → envíe, continuar → continúe, aullar → aúlle: the weak vowel of the
  // stem takes a written accent in the stressed (boot) forms.
  readonly accented: boolean;
  // Irregular yo-stem, used for every present-subjunctive person (tener → teng-).
  readonly presentStem?: string;
  // Six fully irregular present-subjunctive forms (ser → sea …).
  readonly presentForms?: ReadonlyArray<string>;
  // Irregular 3rd-plural preterite; the imperfect subjunctive is built from it.
  readonly pret3pl?: string;
  readonly participles?: ReadonlyArray<string>;
}

type IrregularEntry = Omit<VerbSpec, 'lemma' | 'stemChange' | 'accented'> & {
  readonly stemChange?: StemChange;
};

